-- setup.lua -- write the machine-local `options.lua` from a `.env` file.
--
--   xmake lua setup.lua
--
-- `.env` (git-ignored, see .env.template) may provide:
--   LC_DIR        LuisaCompute source tree (relative to this file, or absolute)
--
-- The result is the same `options.lua` that xmake.lua (and cmake/options.cmake
-- for the CMake build) include at the very beginning; edit it by hand at any
-- time, this script only (re)generates a starting point.
local function read_env_file(filepath)
    local env = {}
    if not os.isfile(filepath) then
        return env
    end
    for line in io.lines(filepath) do
        local key, value = line:match("^([^=]+)=(.*)$")
        if key and value then
            -- strip optional surrounding quotes
            value = value:gsub('^"(.*)"$', "%1")
            env[key:gsub("%s+$", "")] = value
        end
    end
    return env
end

local env = read_env_file(".env")
local lc_dir = env.LC_DIR
if lc_dir and #lc_dir > 0 then
    lc_dir = lc_dir:gsub("\\", "/"):gsub("/+$", "")
else
    -- Default: the submodule path used by xmake.lua / CMakeLists.txt.
    lc_dir = "thirdparty/LuisaCompute"
end

-- Per-machine LuisaCompute options. Keep this list short: it only records what
-- differs from LuisaCompute's own defaults. Override per invocation with
-- `xmake f --lc_cuda_backend=n` etc.
local lc_options = {
    lc_enable_dsl = true,
    lc_enable_gui = true,
    lc_enable_imgui = true,
    lc_enable_tests = false,
    lc_enable_py = false,
    lc_disable_win_message_box = true,
    lc_cuda_backend = true,
    lc_dx_backend = os.is_host("windows"),
    lc_vk_backend = true,
    lc_metal_backend = os.is_host("macosx"),
    lc_enable_unity_build = true,
    lc_enable_pch = true,
}

local file, err = io.open("options.lua", "w")
if not file then
    raise(string.format("cannot write options.lua: %s", err))
end
file:write("-- Generated by `xmake lua setup.lua`; machine-local and git-ignored.\n")
file:write("-- See options.lua.template for the documented form.\n")
file:write(string.format('LC_DIR = "%s"\n\n', lc_dir))
file:write("lc_options = {\n")
local keys = {}
for k in pairs(lc_options) do table.insert(keys, k) end
table.sort(keys)
for _, k in ipairs(keys) do
    file:write(string.format("    %s = %s,\n", k, tostring(lc_options[k])))
end
file:write("}\n")
file:close()
print(string.format("wrote options.lua (LC_DIR = \"%s\")", lc_dir))
